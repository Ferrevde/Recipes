export const recipesApi = {
  list(): Promise<Recipe[]> {
    return Promise.resolve(
      recipeCatalog
        .map(validateRecipe)
        .filter((recipe): recipe is Recipe => recipe !== null),
    );
  },

  byId(id: string): Promise<Recipe | null> {
    return this.list().then(
      (recipes) => recipes.find((recipe) => recipe.id === id) ?? null,
    );
  },
};
